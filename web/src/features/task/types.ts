// 任务浏览器页的视图模型（页面计算、手风琴组件渲染，两边必须同一个形状）。
//
// 单独成文件而不是各写一份 interface：**两份结构会漂移** ——
// 页面加了个字段、组件没加，TS 不会报错（结构兼容），但渲染会静默少一样东西。
import type { Task } from '@/types/task'

/**
 * 一个项目默认最多渲染多少个任务，其余收进「加载更多」。
 *
 * **为什么是 4**：树高度必须由"项目数"决定，而不是由"任务数"决定
 * （SPEC §6.1.1/§6.1.2）。一个项目攒下几十个任务是常态，
 * 展开即渲染全部的话，单次展开就是几十个 RouterLink + 状态点，
 * 而用户真正要找的几乎总是**最近那几次**。
 * 4 是"一眼能扫完、又不至于频繁触发加载更多"的折中。
 *
 * 放在这里而不是各自组件里：侧栏树与移动端任务浏览器页是**同一棵树换容器**
 * （SPEC §6.1.1），阈值各写一份就会出现"手机上 4 个、侧栏 8 个"这种
 * 同一份数据两种行为的漂移。
 */
export const TASKS_PER_PROJECT = 4

/** 一个项目在任务浏览器页里的全部呈现信息（已过滤、已排序） */
export interface BrowserGroup {
  key: string
  /** 项目名（project_id 或路径末段） */
  name: string
  /** 项目绝对路径（title 提示） */
  path: string
  /** 全部（已过滤）任务，**未经截断** —— 计数与聚合都用它 */
  tasks: Task[]
  /**
   * 本次实际渲染的任务（截断后）。
   *
   * 组件一律遍历它，而不是自己 `tasks.slice(0, N)` ——
   * 截断是"看多少"的 UI 决定，但它必须与 `hiddenCount` 出自同一次计算，
   * 否则会出现"列表显示 4 条、按钮说还有 3 条、实际有 1 条"这种对不上。
   */
  visible: Task[]
  /** 被「加载更多」收起来的条数（0 = 没有更多） */
  hiddenCount: number
  open: boolean
  /** 筛选后无匹配任务：置灰且不可展开 */
  dim: boolean
  /** 状态聚合文案（"2 运行中 · 1 失败"） */
  agg: string
}
